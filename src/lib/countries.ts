// Like nameKey() in distilleryNames.ts – repeated here, this module has no imports.
function key(name: string): string {
	return name.trim().toLocaleLowerCase('de-DE');
}

const CODES_BY_KEY: ReadonlyMap<string, string> = new Map([
	...Object.entries(COUNTRY_NAMES).map(([code, name]) => [key(name), code] as const),
	...Object.entries(COUNTRY_SYNONYMS).map(([name, code]) => [key(name), code] as const)
]);

/**
 * The code of a country name from `distillery.country`, ignoring case and
 * surrounding spaces. `null` for names without a code: they count for no
 * country, neither on the map nor in the statistics.
 */
export function countryCode(name: string): string | null {
	return CODES_BY_KEY.get(key(name)) ?? null;
}

/** The German name of a code, `null` for an unknown code. */
export function countryName(code: string): string | null {
	return Object.hasOwn(COUNTRY_NAMES, code) ? COUNTRY_NAMES[code] : null;
}
